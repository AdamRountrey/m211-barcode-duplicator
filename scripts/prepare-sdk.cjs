// Generate the app-local M211 trailer toggle.
// Fail closed when the pinned upstream version/content or patch context changes.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const EXPECTED_VERSION = '3.3.3';
const EXPECTED_SHA256 = '684e74605f1a4f4e2c934622df0f503a0f949b357719397d8f6f6621ced311e3';
const ORIGINAL_FLAG = 'this.printTrailer=!0';
const PATCHED_FLAG = 'this.printTrailer=this.printOptions.printTrailer!==false';
const ORIGINAL_CONTEXT = 'this.printerModel==M.M211?(this.xUPI=203,this.yUPI=203,this.printTrailer=!0,this.nPageProcessingStartLoc=0,this.sendOnePageAtATime=!0)';
const ORIGINAL_COMMAND = 't.printTrailer&&(this._printJobOutputStream=Qe.sendSTXW(this._printJobOutputStream,!0))';
const PATCHED_COMMAND = '(t.printerModel===M.M211||t.printTrailer)&&(this._printJobOutputStream=Qe.sendSTXW(this._printJobOutputStream,t.printTrailer))';

function sha256(bytes) { return crypto.createHash('sha256').update(bytes).digest('hex'); }
function count(text, needle) { return text.split(needle).length - 1; }

function patchBundle(bytes, version) {
  if (version !== EXPECTED_VERSION) throw new Error(`Expected Brady SDK ${EXPECTED_VERSION}; found ${version}. Refusing to adapt an unreviewed version.`);
  const digest = sha256(bytes);
  if (digest !== EXPECTED_SHA256) throw new Error(`Brady SDK source SHA256 mismatch (${digest}). Refusing to adapt changed source.`);
  const source = bytes.toString('utf8');
  if (count(source, ORIGINAL_FLAG) !== 1 || count(source, ORIGINAL_CONTEXT) !== 1 || count(source, PATCHED_FLAG) !== 0) {
    throw new Error('Expected exactly one original M211 trailer assignment in its reviewed constructor context.');
  }
  if (count(source, ORIGINAL_COMMAND) !== 1 || count(source, PATCHED_COMMAND) !== 0) {
    throw new Error('Expected exactly one reviewed trailer command in the page generator.');
  }
  const patched = source.replace(ORIGINAL_FLAG, PATCHED_FLAG).replace(ORIGINAL_COMMAND, PATCHED_COMMAND);
  if (count(patched, PATCHED_FLAG) !== 1 || count(patched, ORIGINAL_FLAG) !== 0 ||
      count(patched, PATCHED_COMMAND) !== 1 || count(patched, ORIGINAL_COMMAND) !== 0 ||
      patched.replace(PATCHED_FLAG, ORIGINAL_FLAG).replace(PATCHED_COMMAND, ORIGINAL_COMMAND) !== source) {
    throw new Error('Unexpected SDK adaptation result.');
  }
  return Buffer.from(patched, 'utf8');
}

function prepareSdk(projectRoot = path.resolve(__dirname, '..'), outputDirectory) {
  const root = path.resolve(projectRoot);
  const sourceDirectory = path.join(root, 'node_modules', '@bradycorporation', 'brady-web-sdk');
  const distDirectory = path.join(sourceDirectory, 'dist');
  const output = outputDirectory ? path.resolve(outputDirectory) : path.join(root, 'vendor', 'brady-web-sdk');
  const sourceReal = fs.realpathSync(sourceDirectory);
  if (output === sourceDirectory || output.startsWith(sourceDirectory + path.sep) || output === sourceReal || output.startsWith(sourceReal + path.sep)) {
    throw new Error('Output must not modify the installed SDK.');
  }
  const packageInfo = JSON.parse(fs.readFileSync(path.join(sourceDirectory, 'package.json'), 'utf8'));
  const original = fs.readFileSync(path.join(distDirectory, 'bundle.js'));
  const patched = patchBundle(original, packageInfo.version);
  const licence = fs.readFileSync(path.join(sourceDirectory, 'LICENSE.md'));
  const provenance = {
    package: '@bradycorporation/brady-web-sdk',
    version: EXPECTED_VERSION,
    upstreamSha256: EXPECTED_SHA256,
    generatedSha256: sha256(patched),
    adaptation: 'M211 printOptions.printTrailer=false explicitly sends STX W 0; all other values send STX W 1. Other printer models retain upstream command behavior.',
    prepareCommand: 'node scripts/prepare-sdk.cjs',
  };

  // Validate all source inputs before creating or replacing any output.
  const files = fs.readdirSync(distDirectory, { withFileTypes: true });
  if (files.some(entry => !entry.isFile())) throw new Error('Unexpected non-file entry in upstream dist directory.');
  const assets = files.map(entry => [entry.name, fs.readFileSync(path.join(distDirectory, entry.name))]);
  fs.mkdirSync(output, { recursive: true });
  for (const [name, bytes] of assets) fs.writeFileSync(path.join(output, name), name === 'bundle.js' ? patched : bytes);
  fs.writeFileSync(path.join(output, 'LICENSE.md'), licence);
  fs.writeFileSync(path.join(output, 'provenance.json'), JSON.stringify(provenance, null, 2) + '\n');
  fs.writeFileSync(path.join(output, 'README.md'), [
    '# App-local Brady Web SDK adaptation',
    '',
    `Source: @bradycorporation/brady-web-sdk ${EXPECTED_VERSION}, installed from npm.`,
    `Original bundle SHA256: ${EXPECTED_SHA256}`,
    `Generated bundle SHA256: ${provenance.generatedSha256}`,
    '',
    'Generated by `node scripts/prepare-sdk.cjs`. Do not edit this directory manually.',
    'The installed npm package is unchanged. All upstream dist assets and licensing notices are retained.',
    '',
    'Two expressions are adapted for the M211: `printOptions.printTrailer === false`',
    'selects false in the constructor, and the page generator explicitly sends STX W 0',
    'using the existing SDK command helper. Undefined or true sends STX W 1 and preserves',
    'the original trailing-space behavior. This is an application adaptation, not an official',
    'public Web SDK setting. Other printer models retain their upstream trailer behavior.',
    '',
    'Brady owns the upstream SDK. See LICENSE.md and the bundled *.LICENSE.txt notices.',
    'Review the upstream license before distributing an adapted copy.',
    '',
  ].join('\n'));
  if (sha256(fs.readFileSync(path.join(distDirectory, 'bundle.js'))) !== EXPECTED_SHA256) throw new Error('Upstream SDK unexpectedly changed during generation.');
  return { outputDirectory: output, ...provenance };
}

module.exports = { EXPECTED_VERSION, EXPECTED_SHA256, ORIGINAL_FLAG, PATCHED_FLAG, ORIGINAL_CONTEXT, ORIGINAL_COMMAND, PATCHED_COMMAND, sha256, patchBundle, prepareSdk };
if (require.main === module) {
  try {
    const result = prepareSdk();
    console.log(`Prepared M211 trailer-aware SDK ${result.version} at ${result.outputDirectory}`);
    console.log(`Generated SHA256: ${result.generatedSha256}`);
  } catch (error) {
    console.error(`SDK preparation failed: ${error.message}`);
    process.exitCode = 1;
  }
}
